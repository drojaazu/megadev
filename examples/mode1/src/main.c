/**
 * Mode 1 example: Main CPU program
 *
 * Detects the Mega CD, brings up the Sub CPU and uses the Boot ROM library
 * from the cartridge: default VDP registers, VRAM clear, text printing and the
 * VBLANK handler. With a disc in the drive, has the Sub CPU load DATA.BIN
 * into Word RAM, by CPU copy and by DMA, and checks what arrived.
 */
#include <main/bios.def.h>
#include <main/bios.h>
#include <main/exvec.h>
#include <main/gate_arr.h>
#include <main/memmap.h>
#include <main/mode1.h>
#include <main/text.h>
#include <main/vdp.h>
#include <stdio.h>
#include <system.h>
#include <types.h>

#include "data_sum.h" // DATA_SIZE, DATA_SUM: generated by the makefile
#include "shared.h"
#include <sub/cdrom.def.h>

typedef struct
{
  u32  size;
  char data[];
} DataChunk;

extern DataChunk const res_sp;

#define PLANE_A_ADDR 0xC000
#define FONT_TILE    0x20

#define print_at(str, x, y) text_print((str), VDP_PLANE_XY(PLANE_A_ADDR, x, y, Width64), FONT_TILE)

// Frames to wait for the Sub CPU to answer a command. Drive init with a disc
// takes a few seconds; without one it never completes.
#define CMD_TIMEOUT 600

// Results, readable from an emulator debugger
volatile u16 mode1_status;       // 0x0100 | mode1_load_sub result, 0x00FF = no Mega CD
volatile u16 mode1_echo;         // last COMSTAT0 value from the Sub CPU
volatile u16 mode1_disc;         // drive init + file list: 0x0100 | result, or DISC_*
volatile u16 mode1_load;         // CPU copy load: 0x0100 | result, or DISC_*
volatile u16 mode1_load_sum;     // word sum of the copy-loaded file, read from Word RAM
volatile u16 mode1_load_dma;     // DMA load: 0x0100 | result, or DISC_*
volatile u16 mode1_load_dma_sum; // word sum of the DMA-loaded file
volatile u16 mode1_file_size;    // low word of the file size the Sub CPU reported

// Main CPU side failures, distinct from the Sub CPU's 0x01xx results
#define DISC_TIMEOUT 0x02FF // no answer from the Sub CPU (no disc: drive init never ends)
#define DISC_NO_WORD_RAM 0x02FE // Word RAM was not handed back
#define DISC_BAD_SUM 0x02FD // file loaded, content wrong

static void print_value(char * buf, char const * fmt, u32 value, u8 x, u8 y)
{
  snprintf(buf, 16, fmt, value);
  print_at(buf, x, y);
}

static void frame()
{
  bios_vblank_wait_default();
  exvec_check_sub();
}

/**
 * Send a command to the Sub CPU and wait for its answer
 * @return 0x0100 | result byte, or DISC_TIMEOUT
 */
static u16 sub_command(u16 cmd)
{
  u16 answer = 0;
  ga_main_reg_comcmd1 = cmd;
  for (u16 t = 0; t < CMD_TIMEOUT; ++t)
  {
    frame();
    answer = ga_main_reg_comstat1;
    if ((answer >> 8) == cmd)
      break;
    answer = 0;
  }
  if (answer == 0)
    return DISC_TIMEOUT;
  ga_main_reg_comcmd1 = 0;
  for (u16 t = 0; t < CMD_TIMEOUT && ga_main_reg_comstat1 != 0; ++t)
    frame();
  return 0x0100 | (answer & 0xFF);
}

/**
 * Wait for the Sub CPU to hand Word RAM back
 * @return true if the Main CPU has Word RAM
 */
static bool wait_word_ram()
{
  for (u16 t = 0; t < CMD_TIMEOUT; ++t)
  {
    if (ga_main_reg_memmode & GA_MAIN_RETURN_2M_MASK)
      return true;
    frame();
  }
  return false;
}

static u16 word_sum(u16 const volatile * p, u32 bytes)
{
  u16 sum = 0;
  for (u32 n = bytes / 2; n > 0; --n)
    sum += *p++;
  return sum;
}

/**
 * Have the Sub CPU load DATA.BIN into Word RAM and check the content
 * @param cmd SP_CMD_LOAD or SP_CMD_LOAD_DMA
 * @param offset where in Word RAM the Sub CPU puts it
 * @param sum receives the word sum read back
 * @return 0x0100 | result, or DISC_*
 */
static u16 load_and_check(u16 cmd, u32 offset, volatile u16 * sum)
{
  ga_main_grant_2m(); // the Sub CPU needs Word RAM to fill it
  u16 const result = sub_command(cmd);
  if (result != (0x0100 | CDROM_RESULT_OK))
    return result;
  mode1_file_size = ga_main_reg_comstat3;
  if (!wait_word_ram())
    return DISC_NO_WORD_RAM;
  *sum = word_sum((u16 const volatile *) (WORD_RAM + offset), DATA_SIZE);
  if (*sum != DATA_SUM)
    return DISC_BAD_SUM;
  return result;
}

static char const * disc_text(u16 result)
{
  switch (result)
  {
    case 0x0100 | CDROM_RESULT_OK: return "OK      ";
    case DISC_TIMEOUT: return "TIMEOUT ";
    case DISC_NO_WORD_RAM: return "NO WRAM ";
    case DISC_BAD_SUM: return "BAD SUM ";
    case 0x0100 | (CDROM_RESULT_NOT_FOUND & 0xFF): return "NO FILE ";
    case 0x0100 | (CDROM_RESULT_LOAD_FAIL & 0xFF): return "LOAD ERR";
    case 0x0100 | (CDROM_RESULT_FILE_LIST_FAIL & 0xFF): return "DIR ERR ";
    default: return "ERROR   ";
  }
}

void main()
{
  char buf[16];

  disable_interrupts();

  bios_load_vdp_regs_default();
  bios_clear_vram();
  bios_clear_tables();
  bios_clear_vsram();

  vdp_ctrl_32 = to_vdp_addr(0) | CRAM_W;
  vdp_data = 0x0000;
  vdp_data = 0x0EEE;

  vdp_load_1bpp_tiles(font8x8, FONT8X8_CHARS, FONT_TILE, 1, 0);

  // the Boot ROM default registers leave the display off
  bios_vdp_disp_enable();

  *exvec_vblank = (void (*)) BIOS_VBLANK_HANDLER;
  enable_interrupts();

  print_at("MODE 1 EXAMPLE", 2, 2);

  if (!mode1_detect())
  {
    mode1_status = 0x00FF;
    print_at("MEGA CD: NOT FOUND", 2, 4);
    for (;;)
      bios_vblank_wait_default();
  }
  print_at("MEGA CD: FOUND", 2, 4);

  // crash handler: Main CPU exceptions, and Sub CPU crashes reported below
  exvec_install();

  u8 const result = mode1_load_sub(res_sp.data, res_sp.size);
  mode1_status = 0x0100 | result;
  print_at(result == MODE1_OK ? "SUB CPU: RUNNING" : "SUB CPU: ERROR", 2, 5);
  print_value(buf, "%02X", result, 20, 5);

  print_at("FRAME:", 2, 7);
  print_at("COMCMD0:", 2, 8);
  print_at("COMSTAT0:", 2, 9);
  print_at("INT2:", 2, 10);

  print_at("DISC:", 2, 12);
  print_at("LOAD:", 2, 13);
  print_at("DMA:", 2, 14);
  print_at("SUM:", 2, 15);
  print_value(buf, "%04X", DATA_SUM, 22, 15);

  // Disc: drive init and the root directory, then the file twice
  if (result == MODE1_OK)
  {
    print_at("WAIT    ", 12, 12);
    mode1_disc = sub_command(SP_CMD_DRIVE);
    print_at(disc_text(mode1_disc), 12, 12);
    if (mode1_disc == (0x0100 | CDROM_RESULT_OK))
    {
      mode1_load = load_and_check(SP_CMD_LOAD, 0, &mode1_load_sum);
      print_at(disc_text(mode1_load), 12, 13);
      print_value(buf, "%04X", mode1_load_sum, 12, 15);
      mode1_load_dma = load_and_check(SP_CMD_LOAD_DMA, SP_DMA_OFFSET, &mode1_load_dma_sum);
      print_at(disc_text(mode1_load_dma), 12, 14);
      print_value(buf, "%04X", mode1_load_dma_sum, 17, 15);
    }
  }

  u16 counter = 0;
  for (;;)
  {
    frame();
    ++counter;
    ga_main_reg_comcmd0 = counter;
    mode1_echo = ga_main_reg_comstat0;
    print_value(buf, "%02X", *(volatile u8 *) BIOS_VBLANK_COUNTER, 12, 7);
    print_value(buf, "%04X", counter, 12, 8);
    print_value(buf, "%04X", mode1_echo, 12, 9);
    print_value(buf, "%04X", ga_main_reg_comstat2, 12, 10);
  }
}
