// Short names for the fixed-width integer types. These are a convenience of
// this example, not part of Megadev; the kit's own headers use the intN_t
// names from types.h.

#ifndef SHORTCUTS_H
#define SHORTCUTS_H

#include <types.h>

typedef int8_t   s8;
typedef int16_t  s16;
typedef int32_t  s32;
typedef uint8_t  u8;
typedef uint16_t u16;
typedef uint32_t u32;

#endif
